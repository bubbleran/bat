import contextlib
import subprocess
from pathlib import Path

import typer

from image_defaults import resolve_registry, resolve_repo_name

# Reserved filename: must match the module name `bat.telemetry.build_policy`
# imports (`from _telemetry_build_policy import ...`). Written into the Docker
# build context right before `docker build` so PyInstaller compiles it into
# the frozen binary, then removed -- it must never live in the agent's own
# source tree.
TELEMETRY_BUILD_POLICY_FILENAME = "_telemetry_build_policy.py"


@contextlib.contextmanager
def _telemetry_build_policy_file(
    context_dir: Path,
    hide_content: bool,
    hide_span_names: bool = False,
):
    """Temporarily write the build-time telemetry redaction floor.

    Yields with the file in place (only when ``hide_content`` is set) so
    ``docker build`` picks it up as build context, then always removes it --
    it is a generated artifact, not something that belongs in the agent's
    source tree or its git history.
    """
    if not (hide_content or hide_span_names):
        yield
        return

    policy_path = context_dir / TELEMETRY_BUILD_POLICY_FILENAME
    if policy_path.exists():
        raise typer.BadParameter(
            f"{policy_path} already exists. This filename is reserved for "
            "`bat build --hide-telemetry-content`; rename or remove it."
        )
    policy_path.write_text(
        "# Generated by `bat build`; do not commit.\n"
        f"TELEMETRY_HIDE_CONTENT_FLOOR = {bool(hide_content)}\n"
        f"TELEMETRY_HIDE_SPAN_NAMES_FLOOR = {bool(hide_span_names)}\n",
        encoding="utf-8",
    )
    try:
        yield
    finally:
        policy_path.unlink(missing_ok=True)


def build_image(
    context: Path = typer.Option(
        Path("."),
        "--context",
        "-C",
        help="Directory used as docker build context and to infer the default repository name.",
    ),
    docker_registry: str | None = typer.Option(
        None,
        "--docker-registry",
        help=(
            "Docker registry hostname. Precedence: --docker-registry > "
            "BAT_DOCKER_REGISTRY env var (or .env in current directory) > default_registry."
        ),
    ),
    repo: str | None = typer.Option(
        None,
        "--repo",
        help=(
            "Image repository path. Precedence: --repo > BAT_DOCKER_REPO env var "
            "(or .env in current directory) > default-repository/<project-name>."
        ),
    ),
    version: str = typer.Option(
        "latest",
        "--version",
        help="Image version, used as the image tag and VERSION build arg.",
    ),
    no_cache: bool = typer.Option(
        False,
        "--no-cache",
        help="Disable docker layer cache during build.",
    ),
    hide_telemetry_span_names: bool = typer.Option(
        False,
        "--hide-telemetry-span-names",
        help=(
            "Bake a span-name redaction floor into the frozen binary: span "
            "names are replaced with the OpenInference span kind, so "
            "LangGraph node names are never exported. Makes traces harder "
            "to read; independent of --hide-telemetry-content."
        ),
    ),
    hide_telemetry_content: bool = typer.Option(
        False,
        "--hide-telemetry-content",
        help=(
            "Bake a telemetry redaction floor into the frozen binary: "
            "prompts/messages/tools are always redacted from exported spans "
            "(token counts, span names and timing still export), and "
            "config.yaml can no longer turn this off at runtime. Use when "
            "shipping the agent as a packaged artifact."
        ),
    ),
) -> None:
    context_dir = context.resolve()
    if not context_dir.is_dir():
        typer.secho(f"Context directory not found: {context_dir}", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1)

    dockerfile_path = context_dir / "Dockerfile"
    if not dockerfile_path.is_file():
        typer.secho(f"Dockerfile not found in context: {dockerfile_path}", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1)

    resolved_registry = resolve_registry(context_dir, docker_registry)
    resolved_repo = resolve_repo_name(context_dir, repo)
    image = f"{resolved_registry}/{resolved_repo}:{version}"

    command = ["docker", "build"]
    if no_cache:
        command.append("--no-cache")
    command.extend(["--build-arg", f"VERSION={version}"])
    command.extend(["--tag", image, "."])

    typer.echo(f"Building Docker image: {image}")
    if hide_telemetry_content:
        typer.secho(
            "Telemetry content redaction floor: ON (baked into the binary, "
            "not overridable by config.yaml).",
            fg=typer.colors.CYAN,
        )
    if hide_telemetry_span_names:
        typer.secho(
            "Telemetry span-name redaction floor: ON (baked into the binary, "
            "not overridable by config.yaml).",
            fg=typer.colors.CYAN,
        )
    try:
        with _telemetry_build_policy_file(
            context_dir, hide_telemetry_content, hide_telemetry_span_names
        ):
            subprocess.run(command, check=True, cwd=context_dir)
    except FileNotFoundError as exc:
        typer.secho("Docker executable not found in PATH.", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1) from exc
    except subprocess.CalledProcessError as exc:
        typer.secho("Docker build failed.", fg=typer.colors.RED, err=True)
        raise typer.Exit(code=exc.returncode or 1) from exc

    typer.secho(f"Docker image built successfully: {image}", fg=typer.colors.GREEN)
